import { newGame, weekdayTrace, weekendTrace } from "../.tmp/engine.mjs";
import { PRESETS, placeLabel } from "../.tmp/engine.mjs";
const p = (s) => PRESETS.find((x) => x.id === "six").build(s.choice);
const male = newGame({ first: "physics", second: ["chemistry", "biology"] }, 1, "normal", true, "m", "x", { col: 2, row: 2 });
const female = newGame({ first: "physics", second: ["chemistry", "biology"] }, 1, "normal", true, "f", "x", { col: 2, row: 2 });
const show = (list) => list.map((t) => t.time + ":" + placeLabel(t.place)).join(" → ");
console.log("男生工作日:", show(weekdayTrace(male, p(male), 0)));
console.log("女生工作日:", show(weekdayTrace(female, p(female), 0)));
console.log("男生的周末:", show(weekendTrace(p(male), 0, "you")));
console.log("陈屿的周末:", show(weekendTrace(p(male), 0, "chenyu")));
console.log("同一个家?", weekendTrace(p(male), 0, "you")[0].place === weekendTrace(p(male), 0, "chenyu")[0].place);
