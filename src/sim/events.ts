// 事件的写作契约：固定模板负责"永远可用"，提示词负责"这一周具体长什么样"
export function buildEventPrompt(
  ev: StoryEvent,
  ctx: { name: string; persona?: string; traits?: string; relation?: number; trend?: string; history?: string[]; recent?: string[] }
) {
  const factText = ev.text.split("{npc}").join(ctx.name).split("同桌").join(ctx.name);
  const base =
    ev.prompt ||
    "你在写一款中国高中生活模拟器的一段场景。\n" +
    "场景：「" + ev.title + "」\n" +
    "事实：" + factText + "\n" +
    "在场的人：" + ctx.name + "\n" +
    "要求：只写这个场景里发生了什么，2–4 句，不写心理总结，不写排比，不用成语堆砌，不出现具体分数。";
  if (!ev.social) return base;

  const hist = (ctx.history || []).slice(-40);
  const recent = (ctx.recent || []).slice(-3);
  return (
    base +
    "\n\n【关于" + ctx.name + "】\n" +
    (ctx.persona ? ctx.persona + "\n" : "") +
    (ctx.traits ? "性格：" + ctx.traits + "\n" : "") +
    "性格是稳定的，不要因为关系变好就写成另一个人；关系只会改变距离感，不会改变说话方式与骨头里的东西。\n" +
    "\n【你们的关系】\n" +
    (typeof ctx.relation === "number" ? "当前关系值 " + Math.round(ctx.relation) + "（0–100，25 是普通同学，60 起有微妙，75 以上是暧昧或恋人）\n" : "") +
    (ctx.trend ? "长期走势：" + ctx.trend + "\n" : "") +
    "\n【互动历史】\n" +
    (hist.length ? hist.join("\n") : "（还没有太多来往）") +
    "\n\n【最近发生的事】\n" +
    (recent.length ? recent.join("\n") : "（无）") +
    "\n要求：这一场要接得上前面的关系状态与走势；如果还很生疏，不要写成熟稔的口吻。"
  );
}

